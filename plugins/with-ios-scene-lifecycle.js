/**
 * Adopt the UIScene life cycle on iOS.
 *
 * iOS 26 turned "this app has not adopted the scene life cycle" from a warning
 * into a hard trap. Built against the iOS 26+ SDK, showmi crashed on a real
 * iOS 27 device the moment UIKit created the window — splash, then gone —
 * while running fine on an iOS 17.5 simulator, where the check does not exist.
 * The backtrace names it exactly:
 *
 *   __UIApplicationEvaluateRuntimeIssueForNoSceneLifecycleAdoption_block_invoke
 *
 * Declaring `UIApplicationSceneManifest` alone is NOT enough — that was tried
 * and crashed identically. UIKit wants a real scene delegate.
 *
 * Expo 57.0.24 ships one (`ExpoAppSceneDelegate`), but nothing wires it up:
 * no template uses it (checked through expo-template-bare-minimum 57.0.26),
 * no config plugin adds it, and no app.json flag enables it. Only its unit
 * tests reference it. So this plugin does the wiring, and should be deleted
 * the moment Expo does it officially.
 *
 * It lives in a plugin rather than in `ios/` because that directory is
 * regenerated by `expo prebuild` — hand edits there vanish, exactly as the
 * Xcode signing settings did.
 *
 * Adopting scenes is also a correctness requirement for sign-in, not just a
 * way to stop the crash. Expo's own comment in ExpoAppSceneDelegate.swift:
 * under the scene life cycle UIKit delivers cold-start URLs in
 * `connectionOptions` rather than in the app delegate's launch options, and
 * React Native's `Linking.getInitialURL()` reads only the latter. Their scene
 * delegate rebuilds them. Without it, an emailed sign-in link that launches
 * the app from cold reaches nobody.
 */

const {
  withInfoPlist,
  withAppDelegate,
  withXcodeProject,
  withDangerousMod,
  IOSConfig,
} = require('@expo/config-plugins');
const fs = require('fs');
const path = require('path');

const SCENE_DELEGATE_FILENAME = 'SceneDelegate.swift';

/**
 * The scene delegate itself is empty: `ExpoAppSceneDelegate` already creates
 * the window from the connecting scene, starts React Native into it, and
 * forwards the life-cycle, URL and user-activity events the app delegate
 * expects. A named subclass exists only so Info.plist has a class to point at.
 *
 * The extension is the other half of the contract. `ExpoAppSceneDelegate`
 * refuses to start (with a `fatalError` naming this exact requirement) unless
 * the app delegate conforms to `ExpoReactNativeFactoryProvider`, because the
 * factory is built by the app delegate while the window now belongs to the
 * scene. The generated AppDelegate already declares `window` and
 * `reactNativeFactory` with the right names and types, so conformance needs
 * no members — only the declaration.
 */
const SCENE_DELEGATE_SOURCE = `// Generated by plugins/with-ios-scene-lifecycle.js — do not edit.
//
// Required by iOS 26+, which traps at launch unless the app adopts the
// UIScene life cycle. See the plugin for the full explanation.

// \`internal import\`, not a bare \`import\`: the generated AppDelegate.swift
// imports Expo at internal access level, and Swift requires every file in a
// module to agree. A bare import here fails the build with "ambiguous
// implicit access level for import of 'Expo'".
internal import Expo
import UIKit

class SceneDelegate: ExpoAppSceneDelegate {}

extension AppDelegate: ExpoReactNativeFactoryProvider {}
`;

/**
 * The window is now created by the scene delegate, so the app delegate must
 * stop creating one of its own — otherwise React Native is started twice,
 * once into each window.
 */
function removeLegacyWindowSetup(contents) {
  const legacyBlock =
    /#if os\(iOS\) \|\| os\(tvOS\)\s*\n\s*window = UIWindow\(frame: UIScreen\.main\.bounds\)\s*\n\s*factory\.startReactNative\([\s\S]*?\)\s*\n#endif\n/;

  if (!legacyBlock.test(contents)) {
    // Already removed, or the template changed shape. Either way, say so
    // loudly rather than silently producing an app that starts React Native
    // twice or not at all.
    if (contents.includes('ExpoAppSceneDelegate') || !contents.includes('window = UIWindow(')) {
      return contents;
    }
    throw new Error(
      '[with-ios-scene-lifecycle] Could not find the legacy window setup in AppDelegate.swift. ' +
        'The Expo template has changed — check whether it now adopts the scene life cycle itself, ' +
        'in which case this plugin should be deleted.',
    );
  }

  return contents.replace(
    legacyBlock,
    '    // The window is created by SceneDelegate under the UIScene life cycle.\n',
  );
}

const withSceneManifest = (config) =>
  withInfoPlist(config, (cfg) => {
    cfg.modResults.UIApplicationSceneManifest = {
      // showmi is a single-window phone app; multiple scenes would mean
      // multiple React Native roots, which the app is not built for.
      UIApplicationSupportsMultipleScenes: false,
      UISceneConfigurations: {
        UIWindowSceneSessionRoleApplication: [
          {
            UISceneConfigurationName: 'Default Configuration',
            // Xcode expands $(PRODUCT_MODULE_NAME) when it processes the
            // plist, giving the Swift class its fully qualified name.
            UISceneDelegateClassName: '$(PRODUCT_MODULE_NAME).SceneDelegate',
          },
        ],
      },
    };
    return cfg;
  });

const withSceneDelegateFile = (config) =>
  withDangerousMod(config, [
    'ios',
    (cfg) => {
      const projectRoot = cfg.modRequest.platformProjectRoot;
      const appName = cfg.modRequest.projectName;
      const target = path.join(projectRoot, appName, SCENE_DELEGATE_FILENAME);
      fs.mkdirSync(path.dirname(target), { recursive: true });
      fs.writeFileSync(target, SCENE_DELEGATE_SOURCE);
      return cfg;
    },
  ]);

const withSceneDelegateInTarget = (config) =>
  withXcodeProject(config, (cfg) => {
    const appName = cfg.modRequest.projectName;
    const groupPath = `${appName}/${SCENE_DELEGATE_FILENAME}`;

    // Writing the file is not enough — Xcode compiles what the project file
    // lists, so it has to join the target's sources build phase too.
    if (!cfg.modResults.hasFile(groupPath)) {
      IOSConfig.XcodeUtils.addBuildSourceFileToGroup({
        filepath: groupPath,
        groupName: appName,
        project: cfg.modResults,
      });
    }
    return cfg;
  });

const withLegacyWindowRemoved = (config) =>
  withAppDelegate(config, (cfg) => {
    cfg.modResults.contents = removeLegacyWindowSetup(cfg.modResults.contents);
    return cfg;
  });

module.exports = function withIosSceneLifecycle(config) {
  // Order matters only for the two file mods: the file must exist on disk
  // before the Xcode project is asked to reference it.
  config = withSceneManifest(config);
  config = withLegacyWindowRemoved(config);
  config = withSceneDelegateFile(config);
  config = withSceneDelegateInTarget(config);
  return config;
};
